def _has_context(text: str, source_key: str, beijing_media: set) -> bool:
    """T3 语境判定：文本含北京语境词，或媒体为北京本地媒体。"""
    if any(w in text for w in CONTEXT_WORDS):
        return True
    return source_key in beijing_media


# “东城区”若紧跟在这些字之后，可能是“邵东城区/桥东城区/东京城区”等
# 其它地名的拼接串，不能直接认定为北京市东城区
_T1_BAD_PREFIX = "邵桥京新城山河湖江岭岗坡湾林平阳永鼓东西南北"

# 街道简称的“前字排除表”：命中词前若出现这些字，说明是别的地名。
# 目前仅“景山”会被“石景山”吞并，其余街道简称暂无需排除。
_PLAIN_BAD_PREFIX = {"景山": "石", "景山街道": "石"}


def _plain_hit(text: str, word: str):
    """返回街道简称的有效首次出现位置；被别的地名吞并时返回 None。"""
    blocked = _PLAIN_BAD_PREFIX.get(word, "")
    start = 0
    while True:
        i = text.find(word, start)
        if i < 0:
            return None
        if not (i > 0 and text[i - 1] in blocked):
            return i
        start = i + 1


def _only_other_district(text: str) -> bool:
    """文本明确指向其它区、且全文未出现“东城”时，不认街道简称命中。"""
    return "东城" not in text and any(d in text for d in _OTHER_DISTRICTS)


def match_dongcheng(title: str, summary: str = "", source_key: str = "",
                    beijing_media: frozenset = frozenset(),
                    trusted: bool = False) -> tuple:
    """判断一条新闻是否与东城区相关。

    返回 (是否相关, 命中关键词, 级别)：
        level 1 = T1 强匹配；2 = T2 独有地标；3 = T3 街道+语境。

    trusted=True 表示该条目来自以"东城区/北京东城"为查询词的搜索源，
    命中 T1 时无需额外北京语境（仍保留地名拼接串防御）。
    """
    text = f"{title or ''} {summary or ''}"
    bm = set(beijing_media)
    # 北京语境：文本出现“北京/首都”、或命中任一独有地标、或来自北京本地媒体
    has_bj = ("北京" in text or "首都" in text
              or any(w in text for w in TIER2) or source_key in bm)

    # T1：强匹配词出现；非可信源需具备北京语境，并排除“邵东城区”等拼接串。
    # 同一文本可能多次出现（先出现拼串、后出现真实地名），需扫描全部命中点。
    for w in TIER1:
        found = False
        start = 0
        while True:
            idx = text.find(w, start)
            if idx < 0:
                break
            if idx == 0 or text[idx - 1] not in _T1_BAD_PREFIX:
                found = True
                break
            start = idx + 1
        if found and (has_bj or trusted):
            return True, w, 1

    # T2：独有地标，全国基本唯一
    for w in TIER2:
        if w in text:
            return True, w, 2
    # T3：街道全名（带"街道"后缀的在全国范围极少重名，直接认可）
    for w in STREETS:
        if _plain_hit(text, w) is not None:
            return True, w, 3
    if _has_context(text, source_key, bm):
        # 明确写的是其它区（如石景山）且全文无“东城”时，街道简称不可作数
        if _only_other_district(text):
            return False, "", 0
        for w in STREET_PLAIN:
            if _plain_hit(text, w) is not None:
                return True, w, 3
    return False, "", 0


def _alias_hit_pos(text: str, alias: str):
    """返回别名在文本中的首个有效位置；无有效命中返回 None。

    “有效”指别名前不是其它区名（排除“朝阳区文旅局”这类拼串）。
    """
    start = 0
    while True:
        i = text.find(alias, start)
        if i < 0:
            return None
        # “区文旅局”这类简称前若紧接其它区名（如“石景山区文旅局”），跳过
        prefix = text[max(0, i - 4):i]
        if not any(d in prefix for d in _OTHER_DISTRICTS):
            return i
        start = i + 1


def match_units(title: str, body: str = "", byline: str = "") -> list:
    """提取涉及单位（最多 5 个，写入 Excel 前取前 3）。

    - title/body：标题与正文（正文富化后传入全文）；
    - byline：署名区文本（记者/通讯员/供稿/供图等，单独传入，
      命中的单位同级优先排前）；
    - 别名命中归一为规范展示名（全称↔简称）；
    - 结果按“级别高在前，同级按首次出现位置排”排序。
    """
    title = title or ""
    body = body or ""
    byline = byline or ""
    # 检索文本：标题 + 正文；署名单独记位置（视为最靠前）
    text = f"{title} {body}"
    # 文档级语境：只有全文出现“东城”时，才允许把“区文旅局”这类泛称
    # 归到东城区；否则同一篇文章里的“区X局”可能是别的区。
    doc_has_dc = "东城" in f"{text} {byline}"
    hits = {}  # canonical -> [rank, best_pos]
    for canon, rank, aliases in UNITS_TABLE:
        best = None
        for a in [canon] + list(aliases):
            if not a:
                continue
            if a.startswith("区") and not doc_has_dc:
                continue
            p = _alias_hit_pos(text, a)
            if p is not None and (best is None or p < best):
                best = p
            # 署名区命中：单位作为供稿/通讯方，视为最靠前
            if byline and a in byline:
                best = -1 if best is None else min(best, -1)
        if best is not None:
            hits[canon] = [rank, best]
    # 包含去重：“东城区委”与“东城区委宣传部”同时命中时保留更具体者
    for a in list(hits.keys()):
        if a in hits and any(a != b and a in b for b in hits):
            del hits[a]
    result = sorted(hits.items(), key=lambda kv: (kv[1][0], kv[1][1]))
    return [canon for canon, _ in result[:5]]


def normalize_unit(name: str) -> str:
    """把历史遗留的单位写法归一到当前规范展示名；未收录原样返回。"""
    name = (name or "").strip()
    if not name:
        return ""
    for canon, _rank, aliases in UNITS_TABLE:
        if name == canon or name in aliases:
            return canon
    return name


def match_category(title: str, body: str = "") -> str:
    """主题分类（Excel 关键词1 列）。"""
    text = f"{title or ''} {body or ''}"
    for name, words in CATEGORIES:
        if any(w in text for w in words):
            return name
    return "综合"


